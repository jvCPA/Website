// Builds preview/index.html from the Apps Script files so the page can be tested without Apps Script.
// Run from the repo root:  node resume/tools/build_preview.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', 'apps-script');
const out = join(here, '..', 'preview', 'index.html');

const read = (name) => readFileSync(join(src, name + '.html'), 'utf8');

// Stand-in for google.script.run. Messages containing the word "fail" simulate a server error.
const mock = `<script>
/* Preview only: assets load from the repo folder and google.script.run is simulated. */
window.RESUME_ASSET_BASE = '../assets/';
window.google = { script: { run: (function () {
  function make(ok, fail) {
    return new Proxy({}, { get: function (_, key) {
      if (key === 'withSuccessHandler') return function (h) { return make(h, fail); };
      if (key === 'withFailureHandler') return function (h) { return make(ok, h); };
      return function (payload) {
        console.info('[preview] google.script.run.' + String(key), payload);
        setTimeout(function () {
          if (/\\bfail\\b/i.test((payload && payload.message) || '')) { if (fail) fail(new Error('Simulated server error (preview).')); }
          else if (ok) ok({ ok: true });
        }, 900);
      };
    } });
  }
  return make();
})() } };
</script>`;

let html = read('Index').replace(/<\?!=\s*include\('(\w+)'\);\s*\?>/g, (_, name) => {
  const body = read(name);
  return name === 'Config' ? body + '\n  ' + mock : body;
});
html = html.replace('<head>', '<head>\n  <!-- Generated by resume/tools/build_preview.mjs from resume/apps-script/. Do not edit by hand. -->');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, html);
console.log('wrote', out);
